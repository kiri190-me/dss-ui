/**
 * 메뉴바가 **받는** 자료의 모양.
 *
 * ── 🔴 이 타입은 dss-auth 의 거울이다 ────────────────────────────────────
 * 원본은 `dss-auth/src/lib/oidc/service-menu.ts` 의 `ServiceMenuEntry` 다.
 * 포털이 로그인 ID 토큰의 `dss_services` 클레임에 싣는 한 칸의 모양이고,
 * 여기 적힌 네 값(id · name · url · icon?)은 **글자 하나까지 그것과 같다**.
 *
 * 왜 import 하지 않고 베껴 적나: 저장소가 서로 독립이라 dss-auth 의
 * 소스를 여기서 부를 수 없다. 베끼는 대신 이름과 선택성(icon 만 ?)을
 * 정확히 맞춰 두면, 사이트는 토큰에서 꺼낸 배열을 **그대로** 넘길 수 있다.
 * 한 글자라도 어긋나면 사이트마다 옮겨 담는 코드가 생기고, 그 코드가
 * 다섯 벌이 되는 순간 이 묶음을 만든 이유가 사라진다.
 *
 * 저쪽이 칸을 늘리면 여기는 그대로 두어도 된다 — 구조적 타입이라 값이 더
 * 들어 있는 객체는 그냥 받아진다. 반대로 저쪽이 이름을 바꾸거나 칸을 빼면
 * 사이트에서 컴파일이 깨진다. 그때 고칠 곳은 이 파일 하나다.
 */
export type ServiceMenuEntry = {
  /**
   * 포털의 clients.client_id. 「지금 여기」를 눌린 상태로 그리기 위한
   * 비교 열쇠다 — 사이트는 자기 client_id(= ID 토큰의 aud)를 알고 있으므로,
   * 그 값을 `currentServiceId` 로 넘기면 자기 칸이 눌린 상태가 된다.
   * 이름이 아니라 식별자로 견주는 이유: 이름은 사람이 바꿀 수 있다.
   */
  id: string;
  /** 사람에게 보이는 이름. 포털 타일(/apps)에 뜨는 것과 같은 이름이어야 한다. */
  name: string;
  /**
   * 눌렀을 때 갈 주소. 포털이 {lan} 같은 자리표시자를 이미 펼친 뒤의
   * 완성된 주소다 — 이 묶음은 주소를 만들지도 고치지도 않는다.
   */
  url: string;
  /**
   * 글자 아이콘(이모지). **없으면 키 자체가 없다** — 포털이 그렇게 싣는다.
   * 그래서 `icon?: string` 이지 `icon: string | null` 이 아니다. 없을 때
   * 무엇을 그릴지는 받는 쪽(이 묶음)이 정한다(ServiceMenuBar 의
   * DEFAULT_SERVICE_ICON).
   */
  icon?: string;
};
