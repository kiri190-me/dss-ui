/**
 * 종이 **받는** 알림 한 줄의 모양.
 *
 * ── 🔴 이 타입은 포털(dss-auth)의 거울이다 ───────────────────────────────
 * 원본은 `dss-auth/src/lib/notifications/merge.ts` 의 `PortalNotificationItem`
 * 이다. 포털이 각 시스템(A/S · 계측기 · 개선요청 …)에 물어 **합친 뒤** 내주는
 * 한 줄의 모양이고, 여기 적힌 아홉 칸은 글자 하나까지 그것과 같다.
 *
 * 왜 import 하지 않고 베껴 적나: 저장소가 서로 독립이라 포털의 소스를 여기서
 * 부를 수 없다(service-menu/types.ts 가 같은 자리에서 같은 이유로 같은 선택을
 * 했다). 베끼는 대신 이름과 선택성을 정확히 맞춰 두면, 사이트는 포털에서 받은
 * 배열을 **그대로** 넘길 수 있다. 한 글자라도 어긋나면 사이트마다 옮겨 담는
 * 코드가 생기고, 그것이 다섯 벌이 되는 순간 이 묶음을 만든 이유가 사라진다.
 *
 * 🔴 **없는 값은 빈 문자열이다**(`?` 가 아니다). 포털이 그렇게 싣는다 —
 * `kind`·`kindLabel`·`detail` 은 받은 답에 없으면 `""` 로 채워져 온다
 * (merge.ts 의 `text(row.kind) ?? ""`). 그래서 이 묶음도 「없음」을 빈
 * 문자열로 읽는다. 무엇을 그리지 **않을지**는 받는 쪽(NotificationBell)이
 * 정한다.
 *
 * 🔴 **`targetKey` 가 없다.** 포털이 일부러 옮기지 않는다 — 그것은 「같은
 * 대상은 한 번만 센다」는 A/S 안쪽 규칙의 재료이고, 받는 쪽이 그것으로 개수를
 * 다시 세면 A/S 의 종과 포털의 종이 서로 다른 숫자를 말하게 된다. 개수는
 * **보낸 쪽이 센 값**을 그대로 쓴다(NotificationBellProps 의 `count`).
 */
export type NotificationBellItem = {
  /**
   * 목록 전체에서 유일한 열쇠. 포털에서는 `client_id:id` 다.
   *
   * 각 시스템의 `id` 는 그 시스템 안에서만 유일하다 — 두 시스템이 같은 id 를
   * 줄 수 있고, 그대로 React key 로 쓰면 종이 줄을 잘못 지운다. 눌린 줄이
   * 어느 줄인지 알아내는 열쇠이기도 하다(BellBehavior).
   */
  key: string;
  /** 어느 시스템에서 왔는가(client_id). 그릴 때 쓰지 않고, 확인 때 넘긴다. */
  sourceId: string;
  /** 그 시스템의 사람이 읽는 이름("A/S 관리" 등). 비면 안 그린다. */
  sourceName: string;
  /** 그 시스템 안에서의 알림 id. 확인 기록의 열쇠가 이 값이다. */
  id: string;
  /**
   * 알림 종류 코드. 🔴 이 묶음은 **어느 시스템의 종류 목록도 모른다** —
   * 코드를 보고 갈라지는 분기가 한 군데도 없고, 색 한 칸을 고르는 데만
   * 쓴다(tone.ts). 종류가 늘어도 이 묶음은 고치지 않는다.
   */
  kind: string;
  /** 사람이 읽는 종류 이름("결재 대기"). 🔴 색과 **함께 글자로도** 그린다. */
  kindLabel: string;
  /** 왼쪽에 굵게 오는 대상 식별자(인수번호 등). */
  subject: string;
  /** 무슨 일인가. 길면 … 로 끝난다. 비면 안 그린다. */
  detail: string;
  /**
   * 누르면 갈 곳. 🔴 **받은 그대로 나간다** — 앞에 무엇도 붙이지 않고 고치지
   * 않는다(보낸 쪽이 이미 완성된 주소로 만들어 보낸다). 여기서 손대면 주소가
   * 두 번 붙어 어디로도 가지 못한다.
   */
  href: string;
};
