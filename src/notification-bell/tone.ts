/**
 * 알림 종류 → **색 한 칸**.
 *
 * ── 🔴 왜 색을 여기서 고르나 ─────────────────────────────────────────────
 * A/S 의 종은 종류마다 글자색이 다르다. 그 색은 그쪽 도메인 표
 * (NOTIFICATION_KIND_META)에 `text-amber-700 dark:text-amber-400` 같은
 * **Tailwind 클래스 이름**으로 적혀 있는데, 그것을 이 묶음으로 옮겨 오면
 * 색이 조용히 사라진다: Tailwind 는 **자기 저장소 소스에서 글자로 찾은
 * 클래스만** CSS 로 만들고, v4 는 node_modules 안을 훑지 않는다. 묶음에서
 * 건너간 클래스 이름은 받는 쪽 빌드에 규칙이 없어 아무 색도 나오지 않는다 —
 * 게다가 **아무 오류도 나지 않아** 한참 뒤에 발견된다.
 *
 * 포털도 같은 이유로 **색을 보내지 않기로** 했다(merge.ts — `kind` 와
 * `kindLabel` 만 싣는다). 그러니 색은 이 묶음이 제 CSS 로 입힌다.
 *
 * ── 🔴 그런데 이 묶음은 어느 시스템의 종류 목록도 모른다 ─────────────────
 * `REPAIR_CASE_APPROVAL` 같은 코드를 여기 적어 두면, 시스템마다 다른 그 목록이
 * 묶음 안으로 들어와 종류가 늘 때마다 이 파일을 고쳐야 한다(그리고 다섯
 * 사이트가 그 판을 따라 올려야 한다). 그래서 **표를 두지 않고 셈으로** 고른다:
 * 종류 코드를 해시해 색 칸 하나를 집는다.
 *
 * 값이 무엇인가:
 *  - **언제나 같다.** 같은 종류는 어느 화면에서도, 새로고침해도 같은 색이다
 *    (순수 함수라 줄과 줄 사이에 기억할 것이 없다).
 *  - **묶음이 종류를 몰라도 된다.** 새 시스템이 새 종류를 보내도 색이 나온다.
 *
 * 맞바꾸는 것(솔직히): 서로 다른 두 종류가 **같은 칸에 앉을 수 있다.** 칸이
 * 16 개뿐이라 종류가 늘면 언젠가 겹친다. 그래도 정보가 사라지지는 않는다 —
 * 종류 **이름을 글자로도 함께** 그리기 때문이다(색은 훑을 때 빨리 갈라 주는
 * 보조 신호이지 유일한 신호가 아니다. 색약이신 분과 흑백 인쇄를 위해서도 그
 * 규칙이 먼저다). 지금 실제로 도는 여덟 종류(A/S)는 서로 겹치지 않는다 —
 * tone.test.ts 가 그 표본으로 확인한다.
 */

/**
 * 색 칸의 수. CSS 에 `--dss-bell-tone-0` … `--dss-bell-tone-15` 로 같은 수만큼
 * 있어야 한다(notification-bell.css.test.ts 가 둘을 맞대 본다).
 *
 * 16 인 까닭: 지금 도는 여덟 종류가 한 칸도 겹치지 않는 가장 작은 수다(그보다
 * 적으면 둘씩 겹친다 — 실제로 세어 보고 골랐다).
 */
export const NOTIFICATION_TONE_COUNT = 16;

/**
 * 종류 코드에서 색 칸 번호(0 … NOTIFICATION_TONE_COUNT-1)를 집는다.
 *
 * FNV-1a 32비트다. 암호용이 아니라 **흩뜨리기용**이라 이만한 것이면 충분하고,
 * 열 줄이 안 되어 어느 언어로 옮겨도 같은 답이 나온다(언젠가 서버 쪽에서 같은
 * 색을 써야 할 때를 생각해 표준 알고리즘을 골랐다).
 *
 * 글자는 코드 포인트로 훑는다 — 이모지(서로게이트 쌍)가 반으로 쪼개져도
 * 답은 나오지만, 쪼개지지 않는 쪽이 「같은 글자면 같은 답」이라는 말에 맞다.
 *
 * 빈 코드(`""`)에도 답이 있다. 그릴 때는 이름(`kindLabel`)이 비면 종류 자체를
 * 안 그리므로 그 색은 쓰이지 않지만, 「어떤 값에도 답한다」가 이 함수의 약속이다.
 */
export function notificationToneIndex(kind: string): number {
  let hash = 2166136261;
  for (const character of kind) {
    hash ^= character.codePointAt(0) ?? 0;
    // Math.imul 이라야 32비트 곱셈이 넘치지 않고 돈다(그냥 * 하면 배정밀도가
    // 되어 아래 자리가 날아간다). >>> 0 으로 매번 부호 없는 32비트로 되돌린다.
    hash = Math.imul(hash, 16777619) >>> 0;
  }
  return hash % NOTIFICATION_TONE_COUNT;
}
