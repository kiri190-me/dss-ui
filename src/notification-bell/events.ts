/**
 * 종이 **펼쳐진** 것을 알리는 창 사건의 이름.
 *
 * ── 🔴 왜 prop 이 아니라 사건인가 ────────────────────────────────────────
 * 「종을 열면 숫자를 다시 세라」는 어느 시스템에나 같은 요구다(배지는 화면이
 * 그려진 순간의 값이라, 열어 보는 순간에는 이미 낡아 있을 수 있다). 그런데
 * 이것을 **함수 prop 하나로만** 두면 서버 컴포넌트에서 종을 그리는 사이트는
 * 쓸 수가 없다 — 클라이언트 경계를 건너는 것은 서버 액션뿐이라, 평범한 함수를
 * 넘기면 React 가 대놓고 오류를 낸다(개선요청이 이미 서버에서 그린다).
 *
 * 사건이면 종을 어디서 그리든 상관없다. 사이트의 **아무 client 조각이나**
 * 창에 귀를 붙여 두면 되고, 듣는 사람이 없으면 아무 일도 일어나지 않는다.
 *
 * 🔴 **이 파일에는 "use client" 가 없다.** 일부러 그렇다 — "use client" 가
 *    붙은 모듈의 export 는 서버에서 읽으면 값이 아니라 「클라이언트 참조」가
 *    되어, 서버 조각이 이 이름을 글자로 쓰지 못하게 된다. 이름만 따로 떼어
 *    두면 서버·클라이언트 어느 쪽에서 불러도 그냥 문자열이다.
 *
 * 쓰는 법(사이트의 client 조각에서):
 * ```tsx
 * useEffect(() => {
 *   const onOpened = () => 다시센다();
 *   addEventListener(BELL_OPENED_EVENT, onOpened);
 *   return () => removeEventListener(BELL_OPENED_EVENT, onOpened);
 * }, []);
 * ```
 *
 * 이름에 `dss:` 를 붙인 까닭: 창은 사이트 전체가 함께 쓰는 자리라, 남의
 * 라이브러리가 쓰는 이름과 겹치지 않아야 한다.
 */
export const BELL_OPENED_EVENT = "dss:bell-opened";
